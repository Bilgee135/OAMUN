                <b style="font-size: 20px;">1. Structure</b>
                <p>The Structure consists of 2 parts: The Header and the Body.</p>
                <b>(a) The Header of the Position Paper must have the following:</b>
                <ul>
                    <li>The Country's name (Not its profile)</li>
                    <li>The Committee's name the paper is for</li>
                    <li>The Topic</li>
                    <li>(OPTIONAL) The Country's flag</li>
                </ul>
                <p>An example is provided below:</p>
                <img style="margin-bottom: 100px; width: 100%" src="../public/images/PPGH.png" />
                <b>(b) The Body of the Position Paper must have the following:</b>
                <ul>
                    <li><b>Historical Background</b>
                        <p>History/Context and recent facts about the situation of the topic. This can include the reasons that led to the topic or facts that have significantly influenced to the current topic. This section is also called the "Context & State Postion"</p>
                    </li>
                    <li><b>Previous actions taken</b>
                        <p>Related UN involvement, policies or other form of action that the country was involved in to address the current topic. This section is also called the "State Role/Past Actions"</p>
                    </li>
                    <li><b>Country's Position and Solution</b>
                        <p>Being the most important part of the paper, this part should consist of rational positions of the country on the current topic and reasonable solutions that can be carried out under the committee. This section is also called the "Solutions"</p>
                    </li>
                </ul>
