                <p class="example-text">
                    "The Central African Republic has been burdened with wars and dictatorships since the
                    1960’s, and despite being endowed with internationally coveted resources such as
                    expansive diamond minds, 73% of its population live on less than US $1 a day. During the
                    past 15 years, life expectancy has declined from 45 to 35 years of age due to poor health
                    care and the HIV/AIDS epidemic which plagues 35% of the CAR’s population. Moreover,
                    the lack of essential drugs and vaccinations has contributed to the recent outbreaks of other
                    diseases such as malaria, tuberculosis, polio and water-borne viruses. The World Health
                    Organization’s resident representative in the Central African Republic stated in a recent
                    interview that the CAR’s health system is “very precarious,” adding that most health
                    workers in rural areas have abandoned their posts because of the region’s insecurity and
                    unpaid wages.<br /><br />
                    Like Zimbabwe and other African nations, the “Brain Drain” migration of health care
                    workers and other trained professionals to the more developed world is significantly
                    contributing to the Central African Republic’s current health situation. Presently, the UN is
                    appealing for $45 million for humanitarian assistance for the CAR, however, the nation
                    anticipates receiving less than a third of that. The CAR recognizes that although there is a
                    need for vaccinations and other salutary goods, the health care system will never be able to
                    reach the thousands of people in need without the physical manpower provided by doctors,
                    nurses and other healthcare workers.<br /><br />
                    At the center of the nation’s policy is the belief that without an international effort, there is
                    no way of solving an international problem. The Central African Republic proposes a
                    resolution which mandates that the subsidy paid by governments to train a doctor or nurse
                    should be calculated, and repaid in an exact amount to the government if that person
                    chooses to migrate. The cost would be paid by the country to which the person is
                    migrating, as it is benefiting from the transfer of “human capital” trained at great cost by
                    the country of origin. However, the CAR also recognizes that income alone will not be
                    sufficient recompense for the lost immigrants and we therefore propose that in developing
                    countries – with a population of migrating workers over a certain percentage – that trained
                    individuals would have to serve a short number of years in their country of origin before
                    being allowed to migrate to practice in a different country. <br /><br />
                    The CAR also recommends that the UN channels funds through organizations like
                    UNESCO, OECD and the World Bank to help improve the wages and living conditions of
                    healthcare workers in third world countries, (like the CAR), who have no other means of
                    financially motivating their citizens to remain and practice in their own nation. The CAR
                    also plans on advocating for a higher percentage of the national GDP to be devoted to
                    research, development, and the promotion of the sciences. Additionally, as an African
                    nation encourages the whole continent to forge a partnership with the diaspora community
                    of Africans worldwide. An effective partnership implies building capacity and exploiting
                    existing capacity within the existing network of highly skilled and expertise African
                    expatriates. Finally, the Central African Republic proposes a resolution that includes the
                    creation of a database on brain drain and capacity building, thus creating knowledge blocks
                    to complement national efforts in addressing deficiencies in education and training
                    capacities as well as trying to maintain and effectively utilize them."
